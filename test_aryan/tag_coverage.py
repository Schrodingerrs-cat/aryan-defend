"""Aggregate every data/<session>/localization_summary.json into data/tag_coverage.md + .csv.

  python3 tag_coverage.py
Run localize_offline.py on a session first (it writes the summary).
"""
import csv
import json
from pathlib import Path

DATA = Path(__file__).resolve().parent / "data"
sums = {}
for d in sorted(p for p in DATA.iterdir() if p.is_dir()):
    f = d / "localization_summary.json"
    if f.exists():
        sums[d.name] = json.loads(f.read_text())
    else:
        sums[d.name] = None   # not processed yet / no video

lines = ["# Which recordings have AprilTags in view", "",
         "Generated by `tag_coverage.py` from `localize_offline.py` output (action-space-hackathon pipeline).",
         "'Map fix' = frames where a tag that is in `map.yaml` gave a position. Stride > 1 means every Nth frame was checked.", "",
         "| Session | Length | Any tag in view | Map fix | Tags seen (frames) | In view but NOT in map | Video time windows with tags (s) |",
         "|---|---|---|---|---|---|---|"]
rows = []
for name, s in sums.items():
    if s is None:
        lines.append(f"| {name} | - | not processed (no video.mp4 or not run) | | | | |")
        continue
    n = max(s["frames_processed"], 1)
    any_pct = 100 * s["frames_with_any_tag"] / n
    tags = ", ".join(f"{k}:{v}" for k, v in s["tag_frames"].items()) or "none"
    win = ", ".join(f"{a:.0f}-{b:.0f}" for a, b in s["tag_windows_s"][:8]) or "-"
    if len(s["tag_windows_s"]) > 8:
        win += f", ... ({len(s['tag_windows_s'])} windows)"
    lines.append(f"| {name} | {s['duration_s']:.0f} s | {any_pct:.0f}% | {s['map_fix_pct']:.0f}% | {tags} "
                 f"| {s['seen_but_unmapped'] or '-'} | {win} |")
    rows.append([name, s["duration_s"], s["stride"], round(any_pct, 1), s["map_fix_pct"], s["lost_pct"],
                 s["longest_gap_without_fix_s"], json.dumps(s["tag_frames"]), json.dumps(s["seen_but_unmapped"]),
                 json.dumps(s["tag_windows_s"])])
lines += ["", "Mapped tags in config/map.yaml: " + ", ".join(
    str(t) for t in next((s["mapped_tags"] for s in sums.values() if s), [])), ""]
(DATA / "tag_coverage.md").write_text("\n".join(lines))
with open(DATA / "tag_coverage.csv", "w", newline="") as f:
    w = csv.writer(f)
    w.writerow(["session", "duration_s", "stride", "any_tag_pct", "map_fix_pct", "lost_pct",
                "longest_gap_s", "tag_frames", "seen_but_unmapped", "tag_windows_s"])
    w.writerows(rows)
print("\n".join(lines))
